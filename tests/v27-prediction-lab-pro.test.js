const assert=require('node:assert/strict');
const {analyzePredictionLab,evaluateTemporalBlend,validProRow}=require('../.test-build/lib/prediction-lab-pro.js');
const {createTrackedPrediction,parseTrackingBackup}=require('../.test-build/lib/tracking.js');
const {forecast}=require('../.test-build/lib/model.js');
const source={id:'tester-12',name:'Max Beispiel',team:'Boston Celtics',position:'G',avg:45,averageL5:45,averageL10:45,proj:45,
  recentScores:[40,45,47,43,41],last5Apps:5,status:'STARTER',playOdds:.95,injuries:0,hasGame:true,nextGame:'2026-11-09 CEL-MIA'};
const p=forecast(source);
const snap={baselinePredicted:45,advancedPredicted:43,intervalP10:10,intervalP90:80,modelVersion:'1.8.0',selectedMode:'classic'};
const original=createTrackedPrediction(p,'nba',new Date('2026-11-01T09:00:00Z'),snap);
assert.equal(original.position,'G');
assert.equal(parseTrackingBackup([original],'nba')[0].position,'G');
assert.equal(parseTrackingBackup([{...original,position:'FAKE'}],'nba')[0].position,undefined);
const empty=analyzePredictionLab([],'nba','all',new Date('2026-12-01T00:00:00Z'));
assert.equal(empty.included,0);assert.equal(empty.baseline,null);assert.equal(empty.candidate.readiness,'collecting');
const record=(day,j,deltaOld=9,deltaNew=2)=>{
  const date=`2026-11-${String(day).padStart(2,'0')}`;
  const actual=35+j;
  return {...original,key:`nba:player-${day}-${j}:${date} LAL-BOS`,playerId:`player-${day}-${j}`,playerName:`Test ${day}-${j}`,position:['G','F','C'][j%3],fixture:`${date} LAL-BOS`,
    savedAt:'2026-10-20T10:00:00Z',actualGameDate:`${date}T22:00:00Z`,actual,actualSource:'sorare',
    predicted:actual+deltaOld,baselinePredicted:actual+deltaOld,advancedPredicted:actual+deltaNew};
};
const rows=Array.from({length:10},(_,i)=>Array.from({length:5},(_,j)=>record(i+1,j))).flat();
const report=analyzePredictionLab(rows,'nba','all',new Date('2026-12-01T00:00:00Z'));
assert.equal(report.included,50);
assert.equal(report.days,10);
assert.equal(report.baseline.mae,9);assert.equal(report.challenger.mae,2);
assert.equal(report.winRate,100);
assert.equal(report.intervalCoverage80,100);
assert.equal(report.candidate.readiness,'promising');
assert.equal(report.candidate.weight,1);
assert.equal(report.candidate.trainingCount,35);
assert.equal(report.candidate.holdoutCount,15);
assert.equal(report.candidate.trainingDays,7);
assert.equal(report.candidate.holdoutDays,3);
assert.equal(report.positionSegments.length,3);
assert.equal(report.scoreSegments.reduce((sum,r)=>sum+r.count,0),50);
assert.equal(report.trends.length,10);
assert.equal(report.misses.length,10);
const only5=analyzePredictionLab(rows,'nba','30',new Date('2026-11-07T00:00:00Z'));
assert.equal(only5.included,30,'future dates are never evaluated');
const none=analyzePredictionLab(rows,'nba','30',new Date('2027-01-01T00:00:00Z'));
assert.equal(none.included,0,'range filter uses result date, never save date');
const invalidDate={...rows[0],savedAt:'2026-12-01T00:00:00Z'};
const wrongFixture={...rows[0],fixture:'2026-11-27 LAL-MIA'};
assert.equal(validProRow(invalidDate,'nba'),false);
assert.equal(validProRow(wrongFixture,'nba'),false);
const manually={...rows[0],actualSource:'manual'};
const oldModel={...rows[0],modelVersion:undefined};
const noScore={...rows[0],actual:null};
const quality=analyzePredictionLab([manually,oldModel,noScore,wrongFixture,rows[0]],'nba','all',new Date('2026-12-01T00:00:00Z'));
assert.equal(quality.included,1);
assert.equal(quality.manualExcluded,1);
assert.equal(quality.noFrozenComparison,1);
assert.equal(quality.unresolved,1);
assert.equal(quality.invalidOfficial,1);
const dup={...rows[0],key:'nba:dup-key',savedAt:'2026-10-25T00:00:00Z',baselinePredicted:500};
const dups=analyzePredictionLab([rows[0],dup],'nba','all',new Date('2026-12-01T00:00:00Z'));
assert.equal(dups.included,1);assert.equal(dups.duplicateExcluded,1);assert.equal(dups.baseline.mae,9,'earliest frozen prediction wins');
const wrongSport=analyzePredictionLab(rows,'football','all',new Date('2026-12-01T00:00:00Z'));
assert.equal(wrongSport.included,0);
const sparse=analyzePredictionLab(rows.slice(0,20),'nba','all',new Date('2026-12-01T00:00:00Z'));
assert.equal(sparse.candidate.readiness,'insufficient');
// A blend selected on training is judged ONLY on the out-of-sample period.
const inverted=rows.map(r=>r.actualGameDate<'2026-11-08' ? r : {...r,advancedPredicted:r.actual+30});
const invertedReport=analyzePredictionLab(inverted,'nba','all',new Date('2026-12-01T00:00:00Z'));
assert.equal(invertedReport.candidate.weight,1,'weight fixed by training, not future');
assert.equal(invertedReport.candidate.readiness,'not-better','holdout failure blocks promotion');
assert.ok(invertedReport.candidate.improvementPercent<0);
const bogusReverse=rows.map(r=>({...r,actualSource:'manual'}));
assert.equal(analyzePredictionLab(bogusReverse,'nba','all',new Date('2026-12-01T00:00:00Z')).included,0);
assert.equal(evaluateTemporalBlend([]).weight,null);
console.log('V2.7 Prediction Lab Pro — frozen archives, dated holdout, filters, duplicate control, error breakdown passed.');
