const assert=require('node:assert/strict');
const fs=require('node:fs');
const {parseSorareBonuses,bestOwnedBonusByPlayer,selectedCardBonus,safeCollection}=require('../.test-build/lib/my-collection');
const {cardsForPlayer,chooseCardAsset}=require('../.test-build/lib/lineup-v29');
const one=parseSorareBonuses([{key:'xp',title:'XP Bonus',bonusBasisPoints:700},{key:'season',title:'In-Season',bonusBasisPoints:500},{key:'collection',title:'Collection',bonusBasisPoints:200}]);
assert.equal(one.bonusPercent,14);assert.equal(one.bonusDetails.length,3);
assert.equal(parseSorareBonuses([]).bonusPercent,null,'Empty bonuses without competition context are unknown, not zero');
assert.equal(parseSorareBonuses(null).bonusPercent,null,'No API bonus data is not zero');
assert.equal(parseSorareBonuses([{bonusBasisPoints:NaN,key:'xp'}]).bonusPercent,null);
assert.equal(parseSorareBonuses([{bonusBasisPoints:-1,key:'xp'}]).bonusPercent,null);
assert.equal(parseSorareBonuses([{bonusBasisPoints:5100,key:'xp'}]).bonusPercent,null,'No silent clipping of large values');
assert.equal(parseSorareBonuses([{key:'XP',title:'XP',bonusBasisPoints:700},{key:'captain',title:'Captain',bonusBasisPoints:5000}]).bonusPercent,7,'Captain bonus must not be counted as a card bonus');
const base={slug:'user',complete:true,syncedAt:'2026-11-04T00:00:00Z'};
const a={assetId:'a',slug:'a',sport:'NBA',playerSlug:'nba-player',playerName:'N',rarity:'limited',seasonYear:2026,serialNumber:1,bonusPercent:6,bonusDetails:[],grade:6};
const b={...a,assetId:'b',slug:'b',rarity:'rare',bonusPercent:13,grade:8};
const c={...a,assetId:'c',slug:'c',sport:'FOOTBALL',playerSlug:'foot-player',bonusPercent:17};
const d={...a,assetId:'d',slug:'d',sport:'FOOTBALL',playerSlug:'foot-player',bonusPercent:null};
const col={...base,cards:[a,b,c,d]};
assert.equal(bestOwnedBonusByPlayer(col,'nba')['nba-player'],13);
assert.equal(bestOwnedBonusByPlayer(col,'football')['foot-player'],17);
assert.deepEqual(bestOwnedBonusByPlayer({...col,complete:false},'football'),{});
const nba=cardsForPlayer(col.cards,'nba','nba-player');assert.equal(nba.length,2);
assert.equal(chooseCardAsset(nba,undefined).assetId,'b','Default highest verifiable card bonus');
assert.equal(chooseCardAsset(nba,'a').assetId,'a','Explicit card selected by user must win');
assert.equal(selectedCardBonus(a,25,0).percent,6,'Sorare bonus supersedes old manual override');
assert.equal(selectedCardBonus(d,25,0).percent,25,'Manual fallback when API bonus missing');
assert.equal(selectedCardBonus(d,undefined,0).percent,0,'Unknown asset cannot inherit bonus from another card');
assert.equal(selectedCardBonus({...a,bonusPercent:0},25,0).percent,0,'Known zero is authoritative');
assert.equal(safeCollection(col,'user').cards.length,4);
const route=fs.readFileSync('app/api/collection/route.ts','utf8');
assert.match(route,/bonuses\s*\{\s*key\s+title\s+bonusBasisPoints\s*\}/);
assert.match(route,/grade/);
assert.match(route,/parseSorareCardBonus\(c\.bonuses,c\.powerBreakdown\)/);
assert.match(route,/ownedByMe:\s*true/);
const dashboard=fs.readFileSync('app/components/arcade-dashboard.tsx','utf8');
assert.match(dashboard,/bonusPercent:\s*effectiveCardStore\[p\.id\]\?\.bonusPercent/);
const builder=fs.readFileSync('app/components/builder-workspace.tsx','utf8');
assert.match(builder,/selectedCardBonus\(asset,customBonus/);
assert.match(builder,/bonus\.source==="sorare"/);
console.log('V2.9.3 official card bonuses, per asset, both sports, no captain double count, safe fallback: OK');
