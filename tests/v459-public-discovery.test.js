const assert = require('node:assert/strict');
const fs = require('node:fs');
const path=require('node:path');
const route=fs.readFileSync(path.join(__dirname,'../app/api/football-live/sorare-scores/route.ts'),'utf8');
const ui=fs.readFileSync(path.join(__dirname,'../features/matches/football-live-center.tsx'),'utf8');
const {matchSorareGame,matchSorarePlayer,parseSorareFootballPhotos,parseSorareFootballScores}=require('../.test-build/lib/football-live-sorare');
assert.match(route,/competitionGames\(fromDate: \$from, toDate: \$to, sport: FOOTBALL\)/,'public all-competition lookup restored');
assert.match(route,/competition\(slug: \$slug\)/,'fallback public competition lookup');
assert.match(route,/teams\(first: 80\)/,'discover Sorare team slugs');
assert.match(route,/homeTeam \{ name slug \} awayTeam \{ name slug \}/,'verified team slugs in public game search');
assert.match(route,/clubs\(slugs: \$slugs\)/,'club lookup');
assert.match(route,/games\(first: 30, startDate: \$start, endDate: \$end\)/,'bounded date-specific team lookup');
assert.match(route,/activePlayers\(first: 70\)/,'independent portrait lookup');
assert.match(route,/const photosFromClubs=photoRows\(rawPortraits\)/,'photos before official score match');
assert.match(route,/photos:photosFromClubs,portraitCandidates/,'unmatched game still returns photos');
assert.match(route,/node\(id: \$id\)/,'global Sorare game lookup');
assert.ok(!route.includes('export const sorareLiveQueries'),'no Next.js extra route exports');
assert.ok(ui.includes('zugeordnete Sorare-Fotos'),'status shows photos without score match');
const target={home:'Crystal Palace',away:'TSG Hoffenheim',date:'2026-11-05T17:45:00Z'};
const game={id:'Game:sorare-public',date:'2026-11-05T17:45:00Z',homeTeam:{name:'Crystal Palace FC'},awayTeam:{name:'TSG Hoffenheim'}};
assert.equal(matchSorareGame([game],target)?.id,game.id);
assert.equal(matchSorareGame([{...game,date:'2026-11-06T17:45:00Z'}],target),null);
assert.equal(matchSorareGame([game,{...game,id:'Game:another'}],target),null);
const sorarePlayers=[{slug:'alexander-prass',displayName:'Alexander Prass',avatarPictureUrl:'https://images.sorare.com/prass.png'},
{slug:'ozan-kabak',displayName:'Ozan Kabak',avatarPictureUrl:'https://images.sorare.com/kabak.png'}];
const photos=parseSorareFootballPhotos(sorarePlayers,[]);
assert.equal(matchSorarePlayer('A. Prass',photos,['A. Prass','O. Kabak'])?.slug,'alexander-prass');
assert.equal(matchSorarePlayer('O. Kabak',photos,['A. Prass','O. Kabak'])?.slug,'ozan-kabak');
const scores=parseSorareFootballScores([{score:71.3,scoreStatus:'PENDING',footballPlayer:sorarePlayers[0]}]);
assert.equal(matchSorarePlayer('A. Prass',scores,['A. Prass'])?.score,71.3);
console.log('V4.5.9 public game discovery, independent portrait and score-matching tests passed');
