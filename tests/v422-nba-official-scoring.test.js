const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {sorareNbaScore,espnStatLine,sorareNbaGameweekBest,parseEspnPlayers}=require('../.test-build/lib/nba-live-core');
const s=(values={})=>({minutes:32,points:0,rebounds:0,assists:0,steals:0,blocks:0,threes:0,turnovers:0,...values});
// Official Sorare scoring matrix: PT 1, REB 1.2, AST 1.5, BLK/STL 3, 3PM 1, TO -2.
assert.equal(sorareNbaScore(s({points:1})),1);
assert.equal(sorareNbaScore(s({rebounds:1})),1.2);
assert.equal(sorareNbaScore(s({assists:1})),1.5);
assert.equal(sorareNbaScore(s({steals:1})),3);
assert.equal(sorareNbaScore(s({blocks:1})),3);
assert.equal(sorareNbaScore(s({threes:1})),1);
assert.equal(sorareNbaScore(s({turnovers:1})),-2,'negative scores must not be clipped');
assert.equal(sorareNbaScore(s({points:10,rebounds:10})),23,'double-double +1');
assert.equal(sorareNbaScore(s({points:10,rebounds:10,assists:10})),39,'triple double adds another +1');
assert.equal(sorareNbaScore(s({points:10,rebounds:10,assists:10,steals:10,blocks:10})),99,'DD and TD awarded only once');
assert.equal(sorareNbaScore(s({points:150})),150,'no artificial individual score cap');
assert.equal(sorareNbaGameweekBest([37.5,47.2,32.1]),47.2,'best game week score, not sum');
assert.equal(sorareNbaGameweekBest([null,null]),null,'missing scores are not zero');
assert.equal(sorareNbaGameweekBest([-2,-5,null]),-2,'negative scores remain negative');
const labels=['MIN','PTS','REB','AST','3PT','STL','BLK','TO'];
const line=(vals)=>espnStatLine(labels,vals);
assert.equal(line(['32:20','30','12','10','3-9','2','1','4']).threes,3);
assert.equal(line(['32:20','30','12','10','0-6','2','1','4']).threes,0);
assert.equal(line(['32:20','30','12','10','--','2','1','4']),null,'unknown 3PM is not zero');
assert.equal(line(['32:20','30','12','10','x-6','2','1','4']),null,'malformed made/attempted is rejected');
assert.equal(line(['32:20','30','12','10','7-6','2','1','4']),null,'made > attempted is rejected');
assert.equal(line(['32:20','30','--','10','3-9','2','1','4']),null,'unavailable rebound is not zero');
assert.equal(line(['--','30','12','10','3-9','2','1','4']),null,'unknown MIN is not presented as exact scoring');
assert.equal(line(['0','0','0','0','0-0','0','0','0']).minutes,0);
assert.equal(espnStatLine(['MIN','PTS','REB','AST','3PM','STL','BLK','TO'],['6:03','8','1','1','2','0','0','1']).threes,2);
const game={home:{id:'11'},away:{id:'22'}};
const raw={boxscore:{players:[{team:{id:'11'},statistics:[{labels,athletes:[{athlete:{id:'100',displayName:'Guard A'},stats:['15:00','5','3','2','--','1','0','1']},{athlete:{id:'101',displayName:'Guard B'},stats:['01:00','0','0','0','0-0','0','0','1']},{athlete:{id:'102',displayName:'Guard C'},stats:['0','0','0','0','0-0','0','0','0']},{athlete:{id:'103',displayName:'Guard D'},stats:['20:00','12','3','3','2-6','0','0','1']}]}]}]}};
const players=parseEspnPlayers(raw,game);
assert.equal(players[0].score,null,'missing 3PM prevents fabricated score');
assert.equal(players[1].score,-2,'played player with turnover only scores -2');
assert.equal(players[2].score,null,'unplayed players remain unknown');
assert.equal(players[3].score,12+3*1.2+3*1.5+2-2);
const ui=fs.readFileSync(path.join(__dirname,'..','features/matches/nba-live-center.tsx'),'utf8');
assert.match(ui,/Sorare Basis\*/);assert.match(ui,/Offizielle NBA-Scoringmatrix anzeigen/);
