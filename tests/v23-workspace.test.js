const assert=require('node:assert/strict');
const {restoreWorkspace,placeInTeam,withinHorizon,gameDate}=require('../.test-build/lib/builder-workspace');
const mk=(id,pos,stars=1)=>({player:{id,name:id,position:pos},stars});
const empty=[null,null,null,null,null];
const saved=restoreWorkspace(null,{selection:['old1',null,null,null,null],presets:{'1':['p1',null,null,null,null]}});
assert.equal(saved.teams.length,4);assert.equal(saved.teams[0].selection[0],'old1');assert.equal(saved.teams[1].selection[0],'p1');
const reloaded=restoreWorkspace({teams:[{selection:['a'],goal:360,collapsed:true}],activeTeamId:'oops'},null);
assert.equal(reloaded.teams[0].goal,360);assert.equal(reloaded.activeTeamId,'team-1');
const reloadedIds=restoreWorkspace({teams:[{id:'team-1',selection:['p']},{id:'team-4',selection:['q']}],activeTeamId:'team-4'},null);
assert.equal(reloadedIds.activeTeamId,'team-4');assert.equal(reloadedIds.teams[1].selection[0],'q');
const cards=[mk('gk','GK'),mk('def','DEF'),mk('fwd','FWD')];
assert.deepEqual(placeInTeam(empty,'gk',cards,'football').selection,['gk',null,null,null,null]);
assert.equal(placeInTeam(empty,'fwd',cards,'football').index,3);
assert.equal(placeInTeam(empty,'gk',cards,'football',2).reason.includes('Position'),true);
assert.equal(placeInTeam(['gk',null,null,null,null],'gk',cards,'football').index,null);
const nba=[mk('a','G',5),mk('b','C',5),mk('c','G',5),mk('d','F',2),mk('e','G',4)];
assert.equal(placeInTeam(['a','b','c',null,null],'d',nba,'nba').reason.includes('16'),true);
assert.equal(placeInTeam(['a','b',null,null,null],'d',nba,'nba').reason,null);
assert.equal(placeInTeam(['a','b','c',null,null],'e',nba,'nba').reason.includes('16'),true);
assert.equal(gameDate({nextGame:'2026-11-05 Example - Other'}).toISOString().slice(0,10),'2026-11-05');
assert.equal(gameDate({nextGame:'2026-14-88 invalid'}),null);
assert.equal(withinHorizon(null,null,new Date()),true);
assert.equal(withinHorizon(null,24,new Date()),false);
console.log('V2.3 Builder Workspace tests: OK');
