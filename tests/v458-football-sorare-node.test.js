const assert=require('node:assert/strict');
const fs=require('node:fs');const path=require('node:path');
const {parseSorareFootballPhotos,parseSorareFootballScores,matchSorareGame,matchSorarePlayer,bestSorarePhoto}=require('../.test-build/lib/football-live-sorare');
const route=fs.readFileSync(path.join(__dirname,'../app/api/football-live/sorare-scores/route.ts'),'utf8');
assert.match(route,/node\(id: \$id\)/,'global Node lookup');
assert.match(route,/\.\.\. on Game/);
assert.ok(!route.includes('competitionGames(fromDate: $from, toDate: $to, sport: FOOTBALL)'));
assert.ok(!route.includes('graphQl(user.session.accessToken,scoreQuery'));
assert.ok(route.includes("!match.id.includes(':')"),'never pass Game:uuid into legacy resolver');
assert.match(route,/avatarPictureUrl fullPictureUrl pictureUrl/);
const photo='https://assets.sorare.com/player.png';
assert.equal(bestSorarePhoto({avatarPictureUrl:photo,pictureUrl:'https://fallback.example/x.png'}),photo);
assert.equal(bestSorarePhoto({avatarPictureUrl:'',fullPictureUrl:photo}),photo);
const photos=parseSorareFootballPhotos([{slug:'alexander-prass',displayName:'Alexander Prass',avatarPictureUrl:photo,pictureUrl:null}],[]);
assert.equal(photos.length,1);assert.equal(photos[0].url,photo);
assert.equal(matchSorarePlayer('A. Prass',photos,['A. Prass','W. Burger'])?.slug,'alexander-prass');
assert.equal(matchSorarePlayer('A. Prass',photos,['A. Prass','Another Prass']),null);
const scores=parseSorareFootballScores([{footballPlayer:{slug:'alexander-prass',displayName:'Alexander Prass'},score:75.5,scoreStatus:'PENDING'}]);
assert.equal(matchSorarePlayer('A. Prass',scores,['A. Prass'])?.score,75.5);
const matched=matchSorareGame([{id:'Game:18b6a9c3-011a-45ae-a5b0-6e64f078fce0',date:'2026-11-05T18:00:00Z',homeTeam:{name:'TSG Hoffenheim'},awayTeam:{name:'Crystal Palace'}}],{home:'Hoffenheim',away:'Crystal Palace',date:'2026-11-05T18:00:00Z'});
assert.equal(matched?.id,'Game:18b6a9c3-011a-45ae-a5b0-6e64f078fce0');
const ui=fs.readFileSync(path.join(__dirname,'../features/matches/football-live-center.tsx'),'utf8');
assert.ok(ui.includes('Sorare-Fotos'));
console.log('V4.5.8 Sorare global ID and portrait-source tests passed');
